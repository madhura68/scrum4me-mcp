describe('collectReleaseMetadata — gate evidence', () => {
  it('rejects an absent required gate', async () => {
    const evidence = new Map<string, string>([
      ['schema', sha256(DEFAULT_SCHEMA)],
      ['typecheck', sha256(DEFAULT_LOCK)],
      ['stdio_canary', sha256(DEFAULT_SURFACE)],
    ])
    const deps = fakeReleaseMetadataDeps({ evidence })

    await expect(collectReleaseMetadata(deps)).rejects.toThrow(
      'GATE_EVIDENCE_MISSING',
    )
  })

  it('rejects an unknown gate key', async () => {
    const evidence = new Map<string, string>([
      ['schema', sha256(DEFAULT_SCHEMA)],
      ['typecheck', sha256(DEFAULT_LOCK)],
      ['tests', 'e'.repeat(64)],
      ['stdio_canary', sha256(DEFAULT_SURFACE)],
      ['deploy', 'f'.repeat(64)],
    ])
    const deps = fakeReleaseMetadataDeps({ evidence })

    await expect(collectReleaseMetadata(deps)).rejects.toThrow(
      'GATE_EVIDENCE_UNKNOWN_KEY',
    )
  })

  it('rejects a malformed (non-sha256) gate digest', async () => {
    const evidence = new Map<string, string>([
      ['schema', sha256(DEFAULT_SCHEMA)],
      ['typecheck', sha256(DEFAULT_LOCK)],
      ['tests', 'not-a-sha'],
      ['stdio_canary', sha256(DEFAULT_SURFACE)],
    ])
    const deps = fakeReleaseMetadataDeps({ evidence })

    await expect(collectReleaseMetadata(deps)).rejects.toThrow(
      'GATE_EVIDENCE_MALFORMED',
    )
  })
})

